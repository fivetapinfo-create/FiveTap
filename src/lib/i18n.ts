export type Lang = "es" | "en";

export function langFrom(acceptLanguage: string | null): Lang {
  const first = (acceptLanguage || "").split(",")[0]?.trim().toLowerCase() || "";
  return first && !first.startsWith("es") ? "en" : "es";
}

